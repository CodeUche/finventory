async function exportProductsPDF(products: Product[], org?: Organisation | null) {
  const { saveBlobFile } = await import('@/lib/saveBlobFile')
  const { applyDocHeader, buildTableStyle, addDocFooter, pdfMoney, COLORS, TYPE } = await import('@/lib/pdfUtils')
  const toRgb = (hex?: string): [number, number, number] => {
    const m = /^#?([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})$/i.exec(hex ?? '')
    if (!m) return [249, 115, 22]
    return [parseInt(m[1], 16), parseInt(m[2], 16), parseInt(m[3], 16)]
  }
  const BRAND = toRgb(org?.brand_color) as [number, number, number]
  const DARK  = COLORS.DARK
  const MUTED = COLORS.MUTED
  const tmpl  = org?.invoice_template ?? 'classic'
  const pdfFont = 'helvetica'
  const displayName = org?.name ?? 'Company'
  const exportedAt = new Date().toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' })
  const doc = new jsPDF({ unit: 'mm', format: 'a4', orientation: 'landscape' })
  doc.setLineHeightFactor(1.15)
  const pageW = doc.internal.pageSize.getWidth()
  let logoData: string | undefined
  const _storedLogo = useAuthStore.getState().logoDataUrl
  if (_storedLogo) { logoData = _storedLogo }
  else if (org?.logo) { try { const r = await fetch(org.logo); const b = await r.blob(); logoData = await new Promise(res => { const fr = new FileReader(); fr.onload = () => res(fr.result as string); fr.readAsDataURL(b) }) } catch { /* skip */ } }
  const y = applyDocHeader(doc, {
    tmpl, pageW, BRAND, DARK, MUTED,
    landscape: true,
    logoData, displayName,
    orgAddress: org?.address, orgEmail: org?.email, orgPhone: org?.phone,
    pdfFont, fontSize: 12, pdfStyle: 'bold', nameColor: tmpl === 'modern' ? DARK : COLORS.WHITE,
    showCompanyName: true, docTitle: 'PRODUCT CATALOGUE',
    metaRows: [
      ['Total Products', String(products.length)],
      ['Exported', exportedAt],
    ],
  })
  const ts = buildTableStyle(BRAND, pdfFont, { landscape: true })
  autoTable(doc, {
    ...ts,
    startY: y,
    tableWidth: 'auto',
    head: [['SKU', 'Product', 'Type', 'Cost Price', 'Selling Price', 'Wholesale Price', 'Stock']],
    body: products.map(p => {
      const cost = parseFloat(p.cost_price) || 0
      const sell = parseFloat(p.selling_price) || 0
      return [
        p.sku ?? '—', p.name, (p as any).product_type ?? 'physical',
        pdfMoney(cost),
        pdfMoney(sell),
        (p as any).wholesale_price && parseFloat((p as any).wholesale_price) > 0
          ? pdfMoney(parseFloat((p as any).wholesale_price)) : '—',
        p.total_stock ?? 0,
      ]
    }),
    columnStyles: {
      0: { cellWidth: 'auto' },                            // SKU
      1: { cellWidth: 'auto' },                            // Product
      2: { cellWidth: 'auto' },                            // Type
      3: { cellWidth: 'auto', halign: 'right' as const }, // Cost Price
      4: { cellWidth: 'auto', halign: 'right' as const }, // Selling Price
      5: { cellWidth: 'auto', halign: 'right' as const }, // Wholesale Price
      6: { cellWidth: 'auto', halign: 'right' as const }, // Stock
    },
    styles: { ...ts.styles, fontSize: 8, cellPadding: 3, overflow: 'linebreak' },
    margin: { left: 10, right: 10 },
  })
  const finalY = (doc as any).lastAutoTable.finalY + 4
  doc.setFontSize(TYPE.TINY.size); doc.setFont(pdfFont, 'normal'); doc.setTextColor(...MUTED)
  doc.text(`Report generated by Audity  ·  ${exportedAt}`, 10, finalY)
  addDocFooter(doc, { orgName: displayName, docTitle: 'PRODUCT CATALOGUE', docRef: '', BRAND, pdfFont, landscape: true })
  await saveBlobFile(doc.output('blob'), `products-catalogue.pdf`)
}

async function exportProductsCSV(products: Product[]) {
  const { saveBlobFile } = await import('@/lib/saveBlobFile')
  const headers = ['SKU', 'Product', 'Type', 'Cost Price', 'Selling Price', 'Wholesale Price', 'Stock']
  const rows = products.map(p => {
    const cost = parseFloat(p.cost_price) || 0
    const sell = parseFloat(p.selling_price) || 0
    return [p.sku ?? '', p.name, (p as any).product_type ?? 'physical', cost, sell,
      (p as any).wholesale_price && parseFloat((p as any).wholesale_price) > 0 ? parseFloat((p as any).wholesale_price) : '',
      p.total_stock ?? 0]
  })
  const csv = [headers, ...rows].map(r => r.map(v => `"${String(v ?? '').replace(/"/g, '""')}"`).join(',')).join('\n')
  await saveBlobFile(new Blob([csv], { type: 'text/csv' }), 'products-catalogue.csv')
}

async function exportProductsExcel(products: Product[]) {
  const { saveBlobFile } = await import('@/lib/saveBlobFile')
  const XLSX = await import('xlsx')
  const headers = ['SKU', 'Product', 'Type', 'Cost Price', 'Selling Price', 'Wholesale Price', 'Stock']
  const rows = products.map(p => {
    const cost = parseFloat(p.cost_price) || 0
    const sell = parseFloat(p.selling_price) || 0
    return [p.sku ?? '', p.name, (p as any).product_type ?? 'physical', cost, sell,
      (p as any).wholesale_price && parseFloat((p as any).wholesale_price) > 0 ? parseFloat((p as any).wholesale_price) : '',
      p.total_stock ?? 0]
  })
  const allRows = [headers, ...rows]
  const ws = XLSX.utils.aoa_to_sheet(allRows)
  // Auto-size each column to fit its widest cell
  ws['!cols'] = headers.map((_, ci) => ({
    wch: Math.max(...allRows.map(r => String(r[ci] ?? '').length)) + 2,
  }))
  const wb = XLSX.utils.book_new()
  XLSX.utils.book_append_sheet(wb, ws, 'Products')
  const buf = XLSX.write(wb, { bookType: 'xlsx', type: 'array' })
  await saveBlobFile(new Blob([buf], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' }), 'products-catalogue.xlsx')
}

